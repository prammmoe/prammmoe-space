import { test, expect } from '@playwright/test'

test('portfolio entrances leave the title readable and keep motion scoped', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-motion', 'cinematic')
  await expect(page.locator('h1')).toHaveCSS('opacity', '1')
  await expect(page.locator('#profile .profile-links')).toHaveAttribute('data-entrance', '3')
  await expect(page.locator('#profile .profile-links')).toHaveCSS('animation-delay', '0.21s')
  await expect(page.locator('[data-entrance="0"]').first()).toHaveCSS('animation-duration', '0.7s')
  for (const route of ['/projects/', '/blog/', '/media/', '/musics/', '/projects/slng/']) {
    await page.goto(route)
    await expect(page.locator('h1')).toHaveAttribute('data-entrance', '0')
    await expect(page.locator('h1')).toHaveCSS('opacity', '1')
  }
  await page.goto('/e-voucher/')
  await expect(page.locator('html')).not.toHaveAttribute('data-motion')
  await expect(page.locator('[data-entrance]')).toHaveCount(0)
})

test('parallax is bounded, independent from reveal, and stops for reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const portrait = page.locator('.portrait-motion')
  const frame = portrait.locator('.parallax-frame')
  await expect.poll(() => frame.evaluate((element) => getComputedStyle(element).transform)).not.toBe('none')
  const before = await frame.evaluate((element) => getComputedStyle(element).transform)
  await page.evaluate(() => scrollTo(0, 200))
  await expect.poll(() => frame.evaluate((element) => getComputedStyle(element).transform)).not.toBe(before)
  expect(await frame.evaluate((element) => Math.abs(new DOMMatrix(getComputedStyle(element).transform).m42))).toBeLessThanOrEqual(12)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(frame).toHaveCSS('transform', 'none')
  await expect(page.locator('[data-scroll-reveal]')).toHaveCount(0)
  await expect(page.locator('h1')).toHaveCSS('animation-name', 'none')
  await page.setViewportSize({ width: 375, height: 812 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(frame).toHaveCSS('transform', 'none')
})

test('theme colors transition only after interaction', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('html')).not.toHaveAttribute('data-theme-transition')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('body')).toHaveCSS('transition-duration', '0.2s, 0.2s')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('html')).not.toHaveAttribute('data-theme-transition')
})

test('blog listing animates but every article stays static', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/blog/')
  await expect(page.locator('h1')).toHaveAttribute('data-entrance', '0')
  const articles = await page.locator('.listing a').evaluateAll((links) => links.map((link) => (link as HTMLAnchorElement).pathname))
  expect(articles.length).toBeGreaterThan(0)
  for (const article of articles) {
    await page.goto(article)
    await expect(page.locator('html')).toHaveAttribute('data-motion', 'none')
    await expect(page.locator('[data-entrance], [data-scroll-reveal], [data-parallax]')).toHaveCount(0)
    await page.locator('.content').scrollIntoViewIfNeeded()
    await expect(page.locator('.content')).toHaveCSS('opacity', '1')
  }
})

test('rapid deck clicks settle and animated dialogs restore focus', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/projects/')
  const deck = page.locator('.screenshot-deck')
  const next = deck.getByRole('button', { name: 'Next PicSweep screenshot' })
  await next.scrollIntoViewIfNeeded()
  await next.click({ clickCount: 3, delay: 20 })
  await expect(deck.locator('.deck-position')).toHaveText('4 / 5')
  await expect.poll(() => deck.evaluate((element) => element.getAnimations({ subtree: true }).filter((animation) => animation.playState === 'running').length)).toBe(0)
  await expect(deck.getByRole('link')).toHaveCount(1)
  await page.goto('/projects/slng/')
  const trigger = page.locator('.screen-full-size').first()
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveCSS('transition-duration', '0.24s')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(dialog).toHaveCSS('transform', 'none')
  await page.mouse.click(2, 2)
  await expect(dialog).not.toBeVisible()
  expect(errors).toEqual([])
})

test('missing observers keep content readable and navigation working', async ({ page }) => {
  await page.addInitScript(() => { Reflect.deleteProperty(window, 'IntersectionObserver') })
  await page.goto('/')
  await expect(page.locator('[data-scroll-reveal]')).toHaveCount(0)
  await expect(page.locator('.parallax-frame').first()).toHaveCSS('transform', 'none')
  await page.getByRole('link', { name: 'All writing', exact: true }).click()
  await expect(page).toHaveURL('/blog/')
  await expect(page.locator('h1')).toHaveCSS('opacity', '1')
})

test('back navigation restores readable content without replaying entrances', async ({ page }) => {
  await page.goto('/')
  const link = page.getByRole('link', { name: 'All writing', exact: true })
  await link.scrollIntoViewIfNeeded()
  await link.click()
  await expect(page).toHaveURL('/blog/')
  await page.goBack()
  await expect(page).toHaveURL('/')
  await expect(link).toBeInViewport()
  await expect(link).toHaveCSS('opacity', '1')
  await expect(page.locator('h1')).toHaveCSS('animation-name', 'none')
})
