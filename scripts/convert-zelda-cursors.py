"""Extract native CUR frames and ANI timing into a browser cursor stylesheet."""
import argparse
import struct
from pathlib import Path


def chunks(data, offset=0):
    while offset + 8 <= len(data):
        tag = data[offset:offset + 4]
        size = struct.unpack_from('<I', data, offset + 4)[0]
        body = data[offset + 8:offset + 8 + size]
        offset += 8 + size + size % 2
        if tag == b'LIST':
            yield from chunks(body, 4)
        else:
            yield tag, body


# Name, native fallback, semantic selectors. data-cursor supports future controls.
STATES = {
    'Normal Select': ('default', 'html'),
    'Link Select': ('pointer', 'a[href], button, summary, [role="button"], input[type="button"], input[type="submit"], input[type="checkbox"], input[type="radio"]'),
    'Text Select': ('text', 'p, h1, h2, h3, h4, h5, h6, li, dt, dd, td, th, pre, code, blockquote, input:not([type]), input[type="text"], input[type="email"], input[type="search"], input[type="password"], input[type="url"], input[type="tel"], input[type="number"], textarea, [contenteditable="true"]'),
    'Help Select': ('help', 'abbr[title]'),
    'Working in Background': ('progress', '[aria-busy="true"]'),
    'Busy': ('wait', ''),
    'Precision Select': ('crosshair', ''),
    'Handwriting': ('cell', ''),
    'Alternate Select': ('alias', ''),
    'Move': ('move', '[draggable="true"]'),
    'Horizontal Resize': ('ew-resize', '[role="separator"][aria-orientation="vertical"]'),
    'Vertical Resize': ('ns-resize', '[role="separator"][aria-orientation="horizontal"]'),
    'Diagonal Resize 1': ('nwse-resize', ''),
    'Diagonal Resize 2': ('nesw-resize', ''),
    'Unavailable': ('not-allowed', ':disabled, [aria-disabled="true"]'),
}

parser = argparse.ArgumentParser()
parser.add_argument('source', type=Path)
args = parser.parse_args()
output = Path('public/cursors/zelda')
output.mkdir(parents=True, exist_ok=True)
rules = []
animations = []
for name, (state, semantic) in STATES.items():
    data = (args.source / f'Zelda - {name}.ani').read_bytes()
    if data[:4] != b'RIFF' or data[8:12] != b'ACON':
        raise ValueError(f'Invalid ANI: {name}')
    parts = list(chunks(data, 12))
    header = struct.unpack('<9I', next(body for tag, body in parts if tag == b'anih'))
    frames = [body for tag, body in parts if tag == b'icon']
    steps = header[2]
    sequence = next((list(struct.unpack(f'<{len(body) // 4}I', body)) for tag, body in parts if tag == b'seq '), list(range(steps)))
    rates = next((list(struct.unpack(f'<{len(body) // 4}I', body)) for tag, body in parts if tag == b'rate'), [header[7]] * steps)
    if len(sequence) != steps or len(rates) != steps or any(index >= len(frames) for index in sequence):
        raise ValueError(f'Invalid frame sequence: {name}')
    for index, frame in enumerate(frames):
        if struct.unpack_from('<HH', frame) != (0, 2):
            raise ValueError(f'Expected CUR frame: {name}')
        (output / f'{state}-{index}.cur').write_bytes(frame)
    def cursor(index):
        return f'url("/cursors/zelda/{state}-{index}.cur"), {state}'
    selectors = [f'[data-cursor="{state}"]']
    if semantic:
        selectors.insert(0, semantic)
    # Interactive ancestors keep their cursor over nested text and icons.
    if state in ('pointer', 'progress', 'not-allowed'):
        selectors.extend(f':is({selector}) *' for selector in list(selectors))
    rule = ':is(' + ', '.join(selectors) + ')'
    rules.append(f'  {rule} {{ cursor: {cursor(sequence[0])}; }}')
    rules.append(f'  {rule}:hover {{ animation: zelda-{state} {sum(rates) / 60:.6f}s steps(1, end) infinite; }}')
    elapsed = 0
    keyframes = []
    for index, rate in zip(sequence, rates):
        keyframes.append(f'  {100 * elapsed / sum(rates):.6f}% {{ cursor: {cursor(index)}; }}')
        elapsed += rate
    keyframes.append(f'  100% {{ cursor: {cursor(sequence[0])}; }}')
    animations.append(f'@keyframes zelda-{state} {{\n' + '\n'.join(keyframes) + '\n}')
css = '/* Generated by scripts/convert-zelda-cursors.py; original hotspots and ANI timing retained. */\n'
css += '@media (hover: hover) and (pointer: fine) {\n' + '\n'.join(rules) + '\n}\n'
css += '\n'.join(animations)
css += '\n@media (prefers-reduced-motion: reduce) {\n  html, html * { animation: none !important; }\n}\n'
css += '@media (forced-colors: active) {\n  html, html * { cursor: revert !important; animation: none !important; }\n}\n'
Path('src/styles/cursors.css').write_text(css)
(output / 'LICENSE.txt').write_text((args.source / 'readme.txt').read_text(encoding='utf-8-sig'))
print(f'Extracted {len(STATES)} cursor states with original timing and hotspots.')
